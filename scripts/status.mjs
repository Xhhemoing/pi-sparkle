import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({ options: {
  root: { type: "string" },
  output: { type: "string" }
} });
const root = resolve(values.root ?? fileURLToPath(new URL("..", import.meta.url)));
const output = resolve(root, values.output ?? "STATUS.md");
const link = (path) => relative(dirname(output), resolve(root, path)).replaceAll("\\", "/");
const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const todo = readFileSync(resolve(root, "tasks/todo.md"), "utf8");

function git(...args) {
  try {
    return execFileSync("git", ["-C", root, ...args], {
      encoding: "utf8", stdio: ["ignore", "pipe", "pipe"]
    }).trim() || "unknown";
  } catch {
    return "unknown";
  }
}

const branch = git("symbolic-ref", "--quiet", "--short", "HEAD");
const commit = git("rev-parse", "--verify", "HEAD");
const repository = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
const github = repository?.match(/^(?:git\+)?https:\/\/github\.com\/([^/]+\/[^/]+?)(?:\.git)?$/)?.[1];
const ci = github ? ` [GitHub Actions](https://github.com/${github}/actions).` : " Repository CI URL unavailable.";
const open = todo.split(/\r?\n/).filter((line) => /^\s*- \[ \] /.test(line));
const tasks = open.map((line) => line.replace(/\]\(([^)]+)\)/g, (match, target) => {
  if (/^(?:[a-z]+:|#|\/)/i.test(target)) return match;
  const [path, anchor] = target.split("#", 2);
  return `](${link(`tasks/${path}`)}${anchor === undefined ? "" : `#${anchor}`})`;
}));

writeFileSync(output, [
  "# Project status",
  "",
  "> Generated by `pnpm status`; do not edit. Snapshot of local inputs at generation time, not a live delivery claim. Worktree dirtiness is intentionally omitted.",
  "",
  `- Version: ${pkg.version} (private: ${pkg.private === true})`,
  `- Branch: ${branch}`,
  `- Commit: ${commit}`,
  `- CI: unknown (not queried; local tests do not establish hosted CI).${ci}`,
  `- Capability evidence: [status matrix](${link("docs/status-matrix.md")})`,
  `- Active work: [checklist](${link("tasks/todo.md")})`,
  "",
  "## Open work",
  "",
  ...(tasks.length ? tasks : ["No unchecked items in the active checklist; this does not imply product acceptance."]),
  ""
].join("\n"), "utf8");
console.log(`status: wrote ${output}`);
